const sqlite3 = require('sqlite3').verbose();
const path = require('path');

// 💡 app.db ගොනුව පිහිටා ඇති නිවැරදි මාර්ගය (Path) සකසා ගැනීම
const dbPath = path.join(__dirname, 'app.db'); 
const db = new sqlite3.Database(dbPath);

db.serialize(() => {
    console.log("⚡ Inserting sample bulk products (Profit will be auto-generated by the database)...");

    // 🛠️ Profit එක නැතුව අනිත් Column ටික විතරක් ඇතුළත් කරන SQL Query එක
    const insertBulkQuery = `
        INSERT INTO bulk_products (BulkProductID, Product_name, Purchase_Price, Sell_Price, Quantity, SupplierID, Barcode) 
        VALUES (?, ?, ?, ?, ?, ?, ?)
    `;

    // 📊 ශ්‍රී ලංකාවේ කිරන බඩු 5ක විස්තර (මෙහි Profit අගයන් ඇතුළත් කර නැත)
    const sampleBulkProducts = [
        ['B1', 'Keeri Samba Rice (1kg)', 240.00, 280.00, 150.50, 'SUP1', '4790001112223'],
        ['B2', 'Nadu Rice (1kg)', 190.00, 220.00, 200.00, 'SUP1', '4790001112224'],
        ['B3', 'Mysoor Dhal / Parippu (1kg)', 280.00, 320.00, 85.75, 'SUP2', '4790001112225'],
        ['B4', 'White Sugar (1kg)', 230.00, 260.00, 120.25, 'SUP3', '4790001112226'],
        ['B5', 'Red Raw Rice (1kg)', 180.00, 210.00, 90.00, 'SUP1', '4790001112227']
    ];

    // 🔄 Loop එකක් මඟින් දත්ත එකින් එක ආරක්ෂිතව ඇතුළත් කිරීම
    sampleBulkProducts.forEach((product) => {
        db.run(insertBulkQuery, product, function(err) {
            if (err) {
                console.error(`❌ Error inserting product ${product[0]}:`, err.message);
            } else {
                console.log(`   ✅ Added bulk product: ${product[1]} (ProductID: ${product[0]})`);
            }
        });
    });

});

// 🔌 වැඩේ ඉවර වුණාම Database Connection එක වසා දැමීම
db.close((err) => {
    if (err) {
        console.error("❌ Error closing database:", err.message);
    } else {
        console.log("🏁 Bulk data insertion completed successfully!");
    }
});